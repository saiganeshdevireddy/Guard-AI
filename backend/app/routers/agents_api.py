"""
Multi-Agent status and messaging API router.
"""
from typing import Any, Dict, Optional
from fastapi import APIRouter, Depends, HTTPException, Query
from pydantic import BaseModel
from sqlalchemy.orm import Session

from app.agents.base import event_bus
from app.agents.controller import controller_ai
from app.database import get_db
from app.security.auth import require_permission

router = APIRouter(prefix="/agents", tags=["Agents"])


class AgentMessageRequest(BaseModel):
    agent_id: str
    message: Dict[str, Any]


@router.get("")
def list_agents(db: Session = Depends(get_db), _user=Depends(require_permission("agents:read"))):
    """Returns real-time status, roles, heartbeats, and metrics for all agents."""
    controller_ai.sync_agent_states_to_db(db)
    return {
        "agents": controller_ai.get_all_agent_states(),
        "total": len(controller_ai.agents),
    }


@router.get("/events")
def get_recent_agent_events(limit: int = Query(default=30, ge=1, le=200), _user=Depends(require_permission("agents:read"))):
    """Returns recent inter-agent communication events from the event bus."""
    return {
        "events": event_bus.get_recent_events(limit=limit)
    }


@router.post("/message")
def send_agent_message(req: AgentMessageRequest, _user=Depends(require_permission("agents:write"))):
    """Sends a direct command to a specific agent."""
    agent = controller_ai.agents.get(req.agent_id)
    if not agent:
        raise HTTPException(status_code=404, detail=f"Agent '{req.agent_id}' not found.")
    response = agent.handle_message(req.message)
    return {
        "agent_id": req.agent_id,
        "response": response,
    }


@router.get("/informer/briefing")
def get_latest_voice_briefing(_user=Depends(require_permission("agents:read"))):
    """Returns the latest natural-language voice briefing generated by Informer AI."""
    return controller_ai.informer.handle_message({"action": "briefing"})
